import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const sourcePath = resolve(root, 'src/data/tools-backlog.json');
const outputPath = resolve(root, 'src/generated/toolRegistry.ts');
const tools = JSON.parse(readFileSync(sourcePath, 'utf8').replace(/^\uFEFF/, ''));
const templates = new Set(['T', 'D', 'F', 'C', 'G', 'R']);
const statuses = new Set(['existing', 'planned', 'live']);
const ids = new Set();

for (const [index, tool] of tools.entries()) {
  const location = `tools-backlog.json entry ${index + 1}`;
  for (const field of ['id', 'name', 'category', 'template', 'description', 'runsLocally', 'library', 'status', 'keywords']) {
    if (!(field in tool)) throw new Error(`${location} is missing ${field}.`);
  }
  if (ids.has(tool.id)) throw new Error(`Duplicate tool id: ${tool.id}`);
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(tool.id)) throw new Error(`Invalid tool id: ${tool.id}`);
  if (!templates.has(tool.template)) throw new Error(`Invalid template for ${tool.id}: ${tool.template}`);
  if (!statuses.has(tool.status)) throw new Error(`Invalid status for ${tool.id}: ${tool.status}`);
  if (!Array.isArray(tool.keywords)) throw new Error(`Keywords must be an array for ${tool.id}.`);
  if (tool.status !== 'planned' && !tool.description.trim()) throw new Error(`Published tool ${tool.id} needs a description.`);
  if (tool.status !== 'planned' && !tool.runsLocally && !tool.provider?.trim()) throw new Error(`Network tool ${tool.id} needs a provider.`);
  ids.add(tool.id);
}

const published = tools.filter((tool) => tool.status !== 'planned');
const categories = [...new Set(published.map((tool) => tool.category))];
const source = `// Generated by scripts/generate-tools.mjs. Edit src/data/tools-backlog.json instead.\n\n` +
`export const toolCategories = ${JSON.stringify(categories, null, 2)} as const;\n` +
`export const toolTemplates = ['T', 'D', 'F', 'C', 'G', 'R'] as const;\n` +
`export const toolStatuses = ['existing', 'planned', 'live'] as const;\n\n` +
`export type ToolCategory = (typeof toolCategories)[number];\n` +
`export type ToolTemplate = (typeof toolTemplates)[number];\n` +
`export type ToolStatus = (typeof toolStatuses)[number];\n\n` +
`export interface ToolMeta {\n` +
`  id: string;\n  name: string;\n  category: ToolCategory;\n  template: ToolTemplate;\n` +
`  description: string;\n  keywords: readonly string[];\n  runsLocally: boolean;\n` +
`  library: string | null;\n  provider?: string;\n  status: ToolStatus;\n  path: string;\n}\n\n` +
`export const toolRegistry = ${JSON.stringify(published.map((tool) => { const generated = { ...tool }; delete generated.batch; return { ...generated, path: `/tools/${tool.id}` }; }), null, 2)} as const satisfies readonly ToolMeta[];\n\n` +
`export const publishedTools = toolRegistry;\n` +
`export const getTool = (id: string): ToolMeta => {\n` +
`  const tool = toolRegistry.find((item) => item.id === id);\n` +
`  if (!tool) throw new Error(\`Unknown tool: \${id}\`);\n  return tool;\n};\n`;

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, source);
console.log(`Validated ${tools.length} tools and generated ${published.length} published entries.`);
